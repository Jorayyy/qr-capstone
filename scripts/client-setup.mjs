#!/usr/bin/env node
/**
 * One-command client setup.
 *
 *   npm run client:setup
 *
 * What it does, in order:
 *   1. Resolves DATABASE_URL / BLOB_READ_WRITE_TOKEN from (in priority order)
 *      --database-url= / --blob-token= flags, environment variables, a local
 *      demo.env file, or interactive prompts.
 *   2. Writes .env with a freshly generated SESSION_SECRET.
 *   3. Installs dependencies if node_modules is missing.
 *   4. Runs prisma generate, prisma migrate deploy, and the seed.
 *   5. Starts `npm run dev`.
 *
 * Flags:
 *   --database-url=...   PostgreSQL URL (skips the prompt)
 *   --blob-token=...     Vercel Blob token (skips the prompt)
 *   --force              Overwrite an existing .env
 *   --no-start           Do not start the dev server
 *   --no-install         Never run npm ci
 *   --skip-seed          Skip the seed step
 */
import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createInterface } from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const envPath = path.join(root, ".env");
const demoEnvPath = path.join(root, "demo.env");

const argv = process.argv.slice(2);
const has = (name) => argv.includes(`--${name}`);
const flag = (name) => {
  const prefix = `--${name}=`;
  const found = argv.find((arg) => arg.startsWith(prefix));
  return found ? found.slice(prefix.length).trim() : undefined;
};

function fail(message) {
  console.error(`\n✖ ${message}\n`);
  process.exit(1);
}

function readEnvFile(file) {
  if (!existsSync(file)) return {};
  const out = {};
  for (const raw of readFileSync(file, "utf8").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const match = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[match[1]] = value;
  }
  return out;
}

function maskDatabaseUrl(url) {
  return url.replace(/(postgres(?:ql)?:\/\/[^:/@]+:)[^@]*@/i, "$1***@");
}

const [major, minor] = process.versions.node.split(".").map(Number);
const supported =
  (major === 20 && minor >= 19) || (major === 22 && minor >= 12) || major >= 24;
if (!supported) {
  console.warn(
    `\n! Node ${process.versions.node} is not supported. Use Node 22.12+ or 24 LTS.\n`
  );
}

const demoVars = readEnvFile(demoEnvPath);
const existingVars = readEnvFile(envPath);

console.log("\n=== Visitor Management System - one-command setup ===\n");
if (existsSync(demoEnvPath)) {
  console.log("• Found demo.env - using the credentials in it.");
}

let databaseUrl =
  flag("database-url") ||
  process.env.DATABASE_URL ||
  existingVars.DATABASE_URL ||
  demoVars.DATABASE_URL;

let blobToken =
  flag("blob-token") ||
  process.env.BLOB_READ_WRITE_TOKEN ||
  existingVars.BLOB_READ_WRITE_TOKEN ||
  demoVars.BLOB_READ_WRITE_TOKEN;

const interactive = Boolean(input.isTTY) && !has("no-prompt");
const rl = interactive ? createInterface({ input, output }) : null;

async function ask(question) {
  if (!rl) return "";
  return ((await rl.question(question)) ?? "").trim();
}

try {
  if (!databaseUrl) {
    if (!interactive) {
      fail(
        "DATABASE_URL is required. Run again with:\n" +
          '  npm run client:setup -- --database-url="postgresql://..."'
      );
    }
    console.log(
      "\nPaste the demo PostgreSQL URL you were given (it starts with postgresql://).\n"
    );
    databaseUrl = await ask("DATABASE_URL: ");
  }

  if (!databaseUrl) fail("DATABASE_URL is required.");

  if (/^mysql:/i.test(databaseUrl)) {
    fail(
      "That is a MySQL URL. XAMPP/MySQL does NOT work with this app - it needs PostgreSQL."
    );
  }
  if (!/^postgres(ql)?:\/\//i.test(databaseUrl)) {
    fail("DATABASE_URL must start with postgresql:// or postgres://");
  }

  if (!blobToken && interactive) {
    console.log(
      "\nPaste the demo Blob token you were given (starts with vercel_blob_rw_),"
    );
    console.log("or press Enter to skip (visitor photo uploads will fail).\n");
    blobToken = await ask("BLOB_READ_WRITE_TOKEN: ");
  }

  const writeEnv = !existsSync(envPath) || has("force");
  if (writeEnv) {
    const sessionSecret = randomBytes(32).toString("hex");
    const lines = [
      "# Generated by npm run client:setup",
      `DATABASE_URL="${databaseUrl}"`,
      `SESSION_SECRET="${sessionSecret}"`,
      'APP_URL="http://localhost:3000"',
      "",
      "# Visitor photo storage (Vercel Blob, private store)",
      blobToken
        ? `BLOB_READ_WRITE_TOKEN="${blobToken}"`
        : '# BLOB_READ_WRITE_TOKEN=""',
      "",
      "# Initial seed passwords (only used the first time a database is seeded)",
      'SEED_ADMIN_PASSWORD="Admin@EVSU2026"',
      'SEED_SECURITY_PASSWORD="Guard@EVSU2026"',
      "",
      "# Optional email (leave unset to show the QR on screen instead)",
      '# SMTP_HOST=""',
      '# SMTP_PORT=""',
      '# SMTP_USER=""',
      '# SMTP_PASS=""',
      '# EMAIL_FROM=""',
      "",
    ];
    writeFileSync(envPath, lines.join("\n"), "utf8");
    console.log("\n✔ .env created.");
  } else {
    console.log("\n• .env already exists - keeping it (use --force to overwrite).");
  }

  console.log(`• Database: ${maskDatabaseUrl(databaseUrl)}`);
  console.log(
    `• Photos:   ${blobToken ? "Blob token configured" : "no Blob token (uploads disabled)"}\n`
  );

  const childEnv = {
    ...process.env,
    DATABASE_URL: databaseUrl,
    BLOB_READ_WRITE_TOKEN: blobToken || "",
    APP_URL: "http://localhost:3000",
    SEED_ADMIN_PASSWORD: process.env.SEED_ADMIN_PASSWORD || "Admin@EVSU2026",
    SEED_SECURITY_PASSWORD:
      process.env.SEED_SECURITY_PASSWORD || "Guard@EVSU2026",
  };

  function run(label, command, options = {}) {
    console.log(`\n▶ ${label}`);
    const result = spawnSync(command, {
      cwd: root,
      env: childEnv,
      stdio: "inherit",
      shell: true,
      ...options,
    });
    if (result.error) fail(`${label} failed: ${result.error.message}`);
    if (result.status !== 0) {
      if (options.allowFailure) return false;
      fail(`${label} failed (exit code ${result.status}).`);
    }
    return true;
  }

  if (!has("no-install") && !existsSync(path.join(root, "node_modules", "next", "package.json"))) {
    const ok =
      run("Installing dependencies (npm ci)", "npm ci --no-audit --no-fund", {
        allowFailure: true,
      }) ||
      run("Installing dependencies (npm install)", "npm install --no-audit --no-fund");
    if (!ok) fail("Could not install dependencies.");
  } else {
    console.log("• Dependencies already installed.");
  }

  run("Generating Prisma client", "npx prisma generate");
  run("Applying database migrations", "npx prisma migrate deploy");

  if (!has("skip-seed")) {
    run("Seeding initial accounts and sample data", "npm run seed");
  }

  if (has("no-start")) {
    console.log("\n✔ Setup complete. Start the system with: npm run dev\n");
  } else {
    console.log("\n✔ Setup complete. Starting the system...");
    console.log("  Open http://localhost:3000  (Ctrl+C to stop)\n");
    run("Starting dev server", "npm run dev");
  }
} finally {
  rl?.close();
}
