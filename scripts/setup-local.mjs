#!/usr/bin/env node
/**
 * Local setup: writes a .env file with a generated SESSION_SECRET.
 *
 * Interactive:   npm run setup
 * Overwrite:     npm run setup -- --force
 * Non-interactive (CI / copy-paste):
 *   DATABASE_URL="postgresql://..." BLOB_READ_WRITE_TOKEN="..." npm run setup
 */
import { createInterface } from "node:readline/promises";
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { stdin as input, stdout as output } from "node:process";

const envPath = new URL("../.env", import.meta.url);
const force = process.argv.includes("--force");

function fail(message) {
  console.error(`\n✖ ${message}\n`);
  process.exit(1);
}

function flag(name) {
  const prefix = `--${name}=`;
  const found = process.argv.find((arg) => arg.startsWith(prefix));
  return found ? found.slice(prefix.length) : undefined;
}

function fromEnv(name) {
  return flag(name) ?? process.env[name];
}

const [major, minor] = process.versions.node.split(".").map(Number);
const supported =
  (major === 20 && minor >= 19) || (major === 22 && minor >= 12) || major >= 24;
if (!supported) {
  console.warn(
    `\n! Node ${process.versions.node} may be unsupported. Use Node 22.12+ or 24 LTS.\n`
  );
}

if (existsSync(envPath) && !force) {
  console.log(
    "\n.env already exists. Delete it first, or run: npm run setup -- --force\n"
  );
  process.exit(0);
}

const interactive = Boolean(input.isTTY);
const rl = interactive ? createInterface({ input, output }) : null;

async function ask(question, fallback) {
  if (!rl) return fallback;
  const answer = await rl.question(question);
  return (answer ?? "").trim() || fallback;
}

try {
  console.log("\n=== Visitor Management System - local setup ===\n");

  let databaseUrl = fromEnv("DATABASE_URL");
  if (!databaseUrl && interactive) {
    databaseUrl = await ask("1) PostgreSQL DATABASE_URL (postgresql://...): ", "");
  }
  if (!databaseUrl) {
    fail(
      'DATABASE_URL is required. Example:\n' +
        '  DATABASE_URL="postgresql://user:pass@host/db?sslmode=require" npm run setup'
    );
  }
  if (/^mysql:/i.test(databaseUrl)) {
    fail(
      "That is a MySQL URL. XAMPP/MySQL does NOT work with this app - it needs PostgreSQL."
    );
  }
  if (!/^postgres(ql)?:\/\//i.test(databaseUrl)) {
    fail("DATABASE_URL must start with postgresql:// or postgres://");
  }

  const blobToken =
    fromEnv("BLOB_READ_WRITE_TOKEN") ??
    (await ask(
      "2) Vercel Blob token (BLOB_READ_WRITE_TOKEN, optional - Enter to skip): ",
      ""
    ));

  const appUrl =
    fromEnv("APP_URL") ??
    (await ask("3) App URL [http://localhost:3000]: ", "http://localhost:3000"));

  const adminPassword =
    fromEnv("SEED_ADMIN_PASSWORD") ??
    (await ask("4) Admin password [Admin@EVSU2026]: ", "Admin@EVSU2026"));
  const guardPassword =
    fromEnv("SEED_SECURITY_PASSWORD") ??
    (await ask("5) Guard password [Guard@EVSU2026]: ", "Guard@EVSU2026"));

  const sessionSecret = randomBytes(32).toString("hex");

  const lines = [
    "# Generated by npm run setup",
    `DATABASE_URL="${databaseUrl}"`,
    `SESSION_SECRET="${sessionSecret}"`,
    `APP_URL="${appUrl || "http://localhost:3000"}"`,
    "",
    "# Visitor photo storage (Vercel Blob, private store)",
    blobToken
      ? `BLOB_READ_WRITE_TOKEN="${blobToken}"`
      : '# BLOB_READ_WRITE_TOKEN=""',
    "",
    "# Initial seed passwords (used only on the first seed run)",
    `SEED_ADMIN_PASSWORD="${adminPassword || "Admin@EVSU2026"}"`,
    `SEED_SECURITY_PASSWORD="${guardPassword || "Guard@EVSU2026"}"`,
    "",
    "# Optional email (leave unset to show the QR on screen instead)",
    '# SMTP_HOST=""',
    '# SMTP_PORT=""',
    '# SMTP_USER=""',
    '# SMTP_PASS=""',
    '# EMAIL_FROM=""',
    "",
  ];

  writeFileSync(envPath, lines.join("\n"), "utf8");

  console.log("\n✔ .env created.\n");
  console.log("Next:");
  console.log("  npm run db:setup");
  console.log("  npm run dev\n");
  if (!blobToken) {
    console.log(
      "! No Blob token: photo uploads will fail. Add BLOB_READ_WRITE_TOKEN later.\n"
    );
  }
} finally {
  rl?.close();
}
